async def update_kol(
    kol_user_id: str,
    account: Account,
    *,
    dry_run: bool,
) -> bool:
    """调用 KOL 接口更新单个 KOL 信息，返回是否成功。"""
    body: dict[str, Any] = {
        "user_id": kol_user_id,          # 有 user_id 则为更新操作
        "nickname": account.account_name,
        "source_platform": SOURCE_PLATFORM,
        "source_user_id": str(account.id),
    }
    if account.account_signature:
        body["description"] = account.account_signature
    if account.avatar_url:
        body["avatar"] = {"url": account.avatar_url}
    if account.hashtags:
        if isinstance(account.hashtags, list):
            body["tags"] = [str(t) for t in account.hashtags if t]
        else:
            body["tags"] = [str(account.hashtags)]

    logger.info(
        "[%s] account=%s name=%r signature=%r avatar=%s tags=%s",
        "DRY" if dry_run else "UPDATE",
        account.id,
        account.account_name,
        (account.account_signature or "")[:50],
        bool(account.avatar_url),
        len(account.hashtags or []),
    )

    if dry_run:
        return True

    client_id = settings.open_api_client_id
    client_secret = settings.open_api_client_secret
    if not client_secret:
        raise RuntimeError("OPEN_API_CLIENT_SECRET 未配置")

    signed_body = sign_params(body, client_id, client_secret)
    url = f"{settings.open_api_base_url.rstrip('/')}/open-api/v1/internal-platform/kol"

    async with httpx.AsyncClient(timeout=30.0, trust_env=False) as client:
        resp = await client.post(url, json=signed_body)

    if resp.status_code >= 400:
        logger.error("  → HTTP %s: %s", resp.status_code, resp.text[:300])
        return False

    payload = resp.json()
    if payload.get("code") not in (0, "0", None):
        logger.error("  → biz error: %s", payload)
        return False

    logger.info("  → OK: %s", payload.get("data") or "")
    return True


async def main(dry_run: bool) -> None:
    kol_ids = [s.strip() for s in KOL_USER_IDS if s.strip()]
    logger.info("共 %d 个 kol_user_id 待处理，dry_run=%s", len(kol_ids), dry_run)

    # 一次性查出所有匹配的账号
    async with SessionLocal() as session:
        rows = (await session.execute(
            select(Account).where(Account.kol_user_id.in_(kol_ids))
        )).scalars().all()

    account_by_kol: dict[str, Account] = {str(a.kol_user_id): a for a in rows}
    logger.info("数据库中找到 %d 个匹配账号", len(account_by_kol))

    ok = fail = skip = 0
    for kol_user_id in kol_ids:
        account = account_by_kol.get(kol_user_id)
        if account is None:
            logger.warning("kol_user_id=%s 在数据库中无对应账号，跳过", kol_user_id)
            skip += 1
            continue

        try:
            success = await update_kol(kol_user_id, account, dry_run=dry_run)
            if success:
                ok += 1
            else:
                fail += 1
        except Exception as exc:
            logger.exception("kol_user_id=%s 更新异常: %s", kol_user_id, exc)
            fail += 1

        # 限速：每次请求间隔 200ms，避免触发下游限流
        await asyncio.sleep(0.2)

    logger.info("完成：ok=%d  fail=%d  skip=%d", ok, fail, skip)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="批量更新 KOL 信息")
    parser.add_argument("--dry-run", action="store_true", help="只打印不调用接口")
    args = parser.parse_args()
    asyncio.run(main(dry_run=args.dry_run))
